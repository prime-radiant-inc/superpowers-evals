#!/usr/bin/env python3
"""Pre-registration power tables for the 2026-08-08 fresh release gate.

Every p-value and power figure quoted in
2026-08-08-fresh-release-gate.md is generated by this script (stdlib
only, no scipy). Regenerate with:  python3 docs/experiments/2026-08-08-fresh-release-gate-power.py
"""
from math import comb

ALPHA = 0.05


def fisher_two_sided(x1: int, n1: int, x2: int, n2: int) -> float:
    """Exact two-sided Fisher p for x1/n1 (main) vs x2/n2 (dev).

    Two-sided by summation of all tables (same margins) whose point
    probability is <= the observed table's, the standard definition.
    """
    k = x1 + x2

    def table_p(a: int) -> float:
        b = k - a
        if b < 0 or b > n2:
            return 0.0
        return comb(n1, a) * comb(n2, b) / comb(n1 + n2, k)

    p_obs = table_p(x1)
    total = 0.0
    for a in range(0, min(n1, k) + 1):
        p = table_p(a)
        if p <= p_obs * (1 + 1e-9):
            total += p
    return total


def power(n1: int, n2: int, p1: float, p2: float, alpha: float = ALPHA) -> float:
    """Exact power of the two-sided Fisher test at true rates p1 (main), p2 (dev)."""
    def binom_pmf(n: int, p: float, x: int) -> float:
        return comb(n, x) * p**x * (1 - p) ** (n - x)

    total = 0.0
    for x1 in range(n1 + 1):
        for x2 in range(n2 + 1):
            if fisher_two_sided(x1, n1, x2, n2) < alpha:
                total += binom_pmf(n1, p1, x1) * binom_pmf(n2, p2, x2)
    return total


def mann_whitney_min_p(n: int) -> float:
    """Exact two-sided p for a complete rank separation, n vs n."""
    return 2.0 / comb(2 * n, n)


FISHER_ROWS = [
    (0, 10, 9, 10), (2, 10, 9, 10), (3, 10, 9, 10), (0, 10, 5, 10),
    (0, 8, 8, 8), (1, 8, 8, 8),
    (0, 6, 6, 6), (1, 6, 6, 6), (2, 6, 6, 6),
    (0, 4, 4, 4), (1, 4, 4, 4),
    (0, 2, 2, 2),
]

POWER_ROWS = [
    ("sdd-escalates n=10/arm, true 2% vs 90%", 10, 10, 0.02, 0.90),
    ("breaker r-a-c n=10/arm, true 2% vs 67%", 10, 10, 0.02, 0.67),
    ("breaker r-a-c n=8/arm, true 2% vs 67%", 8, 8, 0.02, 0.67),
    ("cost-spec pooled n=30/arm (3 cols x 10), true 17% vs 50%", 30, 30, 0.17, 0.50),
    ("cost-spec pooled n=20/arm (2 cols x 10), true 17% vs 50%", 20, 20, 0.17, 0.50),
    ("finishing-branch n=6/arm, true 10% vs 90%", 6, 6, 0.10, 0.90),
    ("wait-mapping n=8/arm, true 5% vs 90%", 8, 8, 0.05, 0.90),
]

if __name__ == "__main__":
    print("## Fisher exact, two-sided (main vs dev)\n")
    print("| split | p |")
    print("|---|---|")
    for x1, n1, x2, n2 in FISHER_ROWS:
        print(f"| {x1}/{n1} vs {x2}/{n2} | {fisher_two_sided(x1, n1, x2, n2):.4f} |")

    print("\n## Exact power at alpha=.05 (two-sided Fisher)\n")
    print("| cell, assumed true rates | power |")
    print("|---|---|")
    for label, n1, n2, p1, p2 in POWER_ROWS:
        print(f"| {label} | {power(n1, n2, p1, p2):.3f} |")

    print("\n## Fractals token rank test (Mann-Whitney exact)\n")
    print("| shape | min two-sided p (complete separation) |")
    print("|---|---|")
    for n in (2, 4, 5):
        print(f"| n={n}/arm | {mann_whitney_min_p(n):.4f} |")
